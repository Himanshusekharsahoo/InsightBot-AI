"""Research Report Export Utilities for InsightBot AI.

Provides structured Markdown and JSON export formatting for saved research sessions,
preserving citations, source URLs, evidence references, and cross-source conflict data.
"""

from typing import Any

from insightbot.db.models import ResearchSession


def format_research_markdown(session: ResearchSession) -> str:
	"""Format a saved research session as an executive Markdown report."""
	md: list[str] = []
	md.append(f'# Research Report: {session.title}')
	md.append('')
	md.append(f'- **Research ID:** `{session.id}`')
	md.append(f'- **Query:** {session.query}')
	md.append(f'- **Status:** `{session.status}`')
	md.append(f'- **Created At:** {session.created_at}')
	if session.completed_at:
		md.append(f'- **Completed At:** {session.completed_at}')
	md.append(f'- **Grounded Synthesis:** {"Yes" if session.is_grounded else "No"}')
	md.append(f'- **Sufficient Evidence:** {"Yes" if session.sufficient_evidence else "No"}')
	if session.error:
		md.append(f'- **Error Detail:** {session.error}')
	md.append('')
	md.append('---')
	md.append('')
	md.append('## Executive Summary')
	md.append('')
	md.append(session.summary if session.summary else '_No summary generated._')
	md.append('')

	# Verified Source Citations
	if session.citations:
		md.append('---')
		md.append('')
		md.append('## Verified Source Citations')
		md.append('')
		for idx, cite in enumerate(session.citations, start=1):
			src_type = cite.get('source_type', 'source').replace('_', ' ').title()
			uri = cite.get('source_uri', 'unknown')
			snippet = cite.get('snippet', '').strip()
			chunk_info = f' (Chunk: `{cite["chunk_id"]}`)' if cite.get('chunk_id') else ''
			md.append(f'{idx}. **[{src_type}]** `{uri}`{chunk_info}')
			if snippet:
				md.append(f'   > {snippet}')
		md.append('')

	# Cross-source Contradictions & Discrepancies
	if session.conflicts:
		md.append('---')
		md.append('')
		md.append('## Cross-Source Contradictions & Discrepancies')
		md.append('')
		for idx, c in enumerate(session.conflicts, start=1):
			topic = c.get('topic', 'Discrepancy')
			desc = c.get('description', '')
			claim_a = c.get('claim_a', '')
			src_a = c.get('source_a', 'Source A')
			claim_b = c.get('claim_b', '')
			src_b = c.get('source_b', 'Source B')
			md.append(f'### {idx}. {topic}')
			if desc:
				md.append(f'- **Description:** {desc}')
			md.append(f'- **Claim A ({src_a}):** {claim_a}')
			md.append(f'- **Claim B ({src_b}):** {claim_b}')
			md.append('')

	# Gathered Evidence
	has_evidence = bool(session.internal_evidence or session.web_evidence)
	if has_evidence:
		md.append('---')
		md.append('')
		md.append('## Gathered Evidence')
		md.append('')
		if session.internal_evidence:
			md.append('### Internal Knowledge Evidence')
			for idx, ev in enumerate(session.internal_evidence, start=1):
				uri = ev.get('source_uri', 'internal_doc')
				cid = ev.get('chunk_id', 'chunk')
				content = ev.get('content', '').strip()
				md.append(f'{idx}. **Source:** `{uri}` (Chunk ID: `{cid}`)')
				if content:
					md.append(f'   > {content}')
			md.append('')

		if session.web_evidence:
			md.append('### Web Research Evidence')
			for idx, we in enumerate(session.web_evidence, start=1):
				url = we.get('source_uri', 'web')
				title = we.get('title')
				title_str = f' - {title}' if title else ''
				content = we.get('content', '').strip()
				md.append(f'{idx}. **URL:** [{url}]({url}){title_str}')
				if content:
					md.append(f'   > {content}')
			md.append('')

	md.append('---')
	md.append('*Generated by InsightBot AI Autonomous Research Engine*')
	return '\n'.join(md)


def format_research_json(session: ResearchSession) -> dict[str, Any]:
	"""Format a saved research session as a structured JSON export dictionary."""
	return session.model_dump()


__all__ = [
	'format_research_markdown',
	'format_research_json',
]
